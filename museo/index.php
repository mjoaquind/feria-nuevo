        <div class="text-justify p-2">
          <p>Bajo la denominación “Museo de Ciencias Naturales” abrió sus puertas el 4 de noviembre del 2010 luego de una ardua y constante labor de sus pioneros. El museo es un espacio de exhibición y montaje referido a las ciencias naturales siendo un atrayente invaluable para la educación formal e informal ya que ofrece el acceso al conocimiento y su divulgación de una manera distinta, con una alta cuota de recreación, y que en cierta forma rompe con los métodos tradicionales de enseñanza utilizados en las escuelas e institutos de educación.</p>
          <p>Aprobado por Resolución 595/07, este espacio tiene como propósitos difundir el conocimiento sobre aspectos naturales de la región, instando a su rescate, conservación y defensa; así como también, apoyar las actividades de educación formal y no formal de los establecimientos escolares y universitarios de la ciudad, proporcionando recursos didácticos y de investigación a los estudiantes que lo visitan. Asimismo, el museo significa un polo estratégico para encabezar o apoyar estudios ecológicos, zoológicos, botánicos, geológicos y paleontológicos a nivel regional.</p>
          <p>Las colecciones con las que cuenta se lograron gracias al aporte desinteresado de varios colaboradores que gentilmente las cedieron para su montaje y exhibición.</p>
